/**
 * /nexa-shot.ts: added to the preview inside NEXA AI (never stored in the project).
 * About 3 seconds after the preview has loaded it takes ONE small picture of the page (the part you
 * see first) and hands it to the builder page, which keeps it as the cover of the project card.
 * It does nothing on published sites, on a narrow preview, or if anything goes wrong.
 * The picture is made by the "html-to-image" library, which this file loads itself from a CDN.
 */
const LINES = [
  'import { NEXA } from "./nexa-config";',
  "",
  'const LIB = "https://cdn.jsdelivr.net/npm/html-to-image@1.11.11/dist/html-to-image.js";',
  'const BLANK = "data:image/gif;base64,R0lGODlhAQABAIAAAMLCwgAAACH5BAAAAAAALAAAAAABAAEAAAICRAEAOw==";',
  "",
  "function snap(lib: any) {",
  "  if (!lib || typeof lib.toJpeg !== \"function\") return;",
  "  const w = window.innerWidth;",
  "  const h = Math.round(Math.min(window.innerHeight, w * 0.625));",
  "  if (w < 700 || h < 200) return;",
  "  const bg = getComputedStyle(document.body).backgroundColor;",
  "  const solid = bg && bg !== \"rgba(0, 0, 0, 0)\" ? bg : \"#ffffff\";",
  "  lib",
  "    .toJpeg(document.body, {",
  "      width: w,",
  "      height: h,",
  "      canvasWidth: 640,",
  "      canvasHeight: Math.round((640 * h) / w),",
  "      quality: 0.62,",
  "      backgroundColor: solid,",
  "      skipFonts: true,",
  "      cacheBust: false,",
  "      imagePlaceholder: BLANK,",
  "    })",
  "    .then((data: string) => {",
  "      if (typeof data === \"string\" && data.length < 120000) window.parent.postMessage({ nexaShot: true, data }, \"*\");",
  "    })",
  "    .catch(() => {});",
  "}",
  "",
  "function capture() {",
  "  try {",
  "    if (window.innerWidth < 700 || document.hidden) return;",
  "    const have = (window as any).htmlToImage;",
  "    if (have) return snap(have);",
  "    const s = document.createElement(\"script\");",
  "    s.src = LIB;",
  "    s.onload = () => snap((window as any).htmlToImage);",
  "    s.onerror = () => {};",
  "    document.head.appendChild(s);",
  "  } catch {",
  "    // a missing cover picture is fine",
  "  }",
  "}",
  "",
  "function start() {",
  "  try {",
  "    // Only in the preview of the builder: no site id, and we are inside another page.",
  "    if (NEXA.site || window.parent === window) return;",
  "    setTimeout(capture, 3500);",
  "  } catch {",
  "    // ignore",
  "  }",
  "}",
  "",
  'if (document.readyState === "complete") start();',
  'else window.addEventListener("load", start);',
  "",
  "export {};",
];

export const SHOT_SOURCE = LINES.join("\n") + "\n";
