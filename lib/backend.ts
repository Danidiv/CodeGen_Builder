/**
 * Backend for generated sites (step 1: form submissions, step 2: saved data per visitor with db()).
 *
 * Generated code does:  import { submitForm, db } from "./nexa";
 * Two small files are added to the Sandpack project at run time (they are NOT stored in the
 * project): /nexa.ts (the SDK below) and /nexa-config.ts (which site, which database).
 *  - Preview inside the builder: no site id -> "test mode", nothing is sent.
 *  - Published site (/s/<id>): submissions go to the database function submit_form()
 *    with the public anon key (see supabase/schema.sql).
 * No secret is ever put into these files: the anon key is public by design.
 */
export type BackendConfig = { site: string; url: string; key: string };

// Written with plain strings (no template literals) so it can be pasted into a template safely.
const SDK_LINES = [
  'import { NEXA } from "./nexa-config";',
  "",
  "export type SubmitResult = { ok: boolean; error?: string; test?: boolean };",
  "",
  "/** Sends a form to the site owner. form = short name (contact, newsletter...), data = text fields. */",
  "export async function submitForm(form: string, data: Record<string, unknown>): Promise<SubmitResult> {",
  "  const clean: Record<string, string> = {};",
  "  for (const [k, v] of Object.entries(data || {})) {",
  '    if (v === undefined || v === null || v === "") continue;',
  "    clean[String(k).slice(0, 60)] = String(v).slice(0, 2000);",
  "  }",
  '  if (Object.keys(clean).length === 0) return { ok: false, error: "Please fill in the form." };',
  "",
  "  if (!NEXA.site) {",
  "    // Preview mode: nothing is sent. Publish the site to receive real submissions.",
  "    try {",
  '      const key = "nexa-test-submissions";',
  '      const list = JSON.parse(localStorage.getItem(key) || "[]");',
  "      list.push({ form, data: clean, at: Date.now() });",
  "      localStorage.setItem(key, JSON.stringify(list.slice(-50)));",
  "    } catch {",
  "      // storage may be blocked",
  "    }",
  '    console.info("[NEXA] Test mode: this form was not saved. Publish the site to receive real submissions.", form, clean);',
  "    return { ok: true, test: true };",
  "  }",
  "",
  "  try {",
  '    const res = await fetch(NEXA.url + "/rest/v1/rpc/submit_form", {',
  '      method: "POST",',
  '      headers: { "Content-Type": "application/json", apikey: NEXA.key, Authorization: "Bearer " + NEXA.key },',
  "      body: JSON.stringify({ p_site: NEXA.site, p_form: String(form).slice(0, 40), p_data: clean }),",
  "    });",
  "    if (!res.ok) {",
  '      let msg = "";',
  "      try {",
  "        msg = String((await res.json()).message || \"\");",
  "      } catch {",
  "        // not json",
  "      }",
  '      if (/too many/i.test(msg)) return { ok: false, error: "Too many messages right now. Please try again later." };',
  '      return { ok: false, error: "Could not send. Please try again." };',
  "    }",
  "    return { ok: true };",
  "  } catch {",
  '    return { ok: false, error: "No connection. Please try again." };',
  "  }",
  "}",
  "",
  "export type Row = { id: string; createdAt: string; [field: string]: unknown };",
  "",
  "let memoryVisitor = \"\";",
  "function visitorKey(): string {",
  "  const ok = (k: string | null) => !!k && /^[a-z0-9]{16,64}$/.test(k);",
  "  try {",
  "    let k = localStorage.getItem(\"nexa-visitor\");",
  "    if (!ok(k)) {",
  "      k = randomId(24);",
  "      localStorage.setItem(\"nexa-visitor\", k);",
  "    }",
  "    return k as string;",
  "  } catch {",
  "    if (!memoryVisitor) memoryVisitor = randomId(24);",
  "    return memoryVisitor;",
  "  }",
  "}",
  "",
  "function randomId(bytes: number): string {",
  "  const a = new Uint8Array(bytes);",
  "  if (typeof crypto !== \"undefined\" && crypto.getRandomValues) crypto.getRandomValues(a);",
  "  else for (let i = 0; i < bytes; i++) a[i] = Math.floor(Math.random() * 256);",
  "  return Array.from(a, (b) => b.toString(16).padStart(2, \"0\")).join(\"\");",
  "}",
  "",
  "function cleanFields(data: Record<string, unknown>): Record<string, unknown> {",
  "  const out: Record<string, unknown> = {};",
  "  for (const [k, v] of Object.entries(data || {})) {",
  "    if (k === \"id\" || k === \"createdAt\" || v === undefined || typeof v === \"function\") continue;",
  "    out[String(k).slice(0, 60)] = v;",
  "  }",
  "  return JSON.parse(JSON.stringify(out));",
  "}",
  "",
  "async function rpc(name: string, args: Record<string, unknown>): Promise<any> {",
  "  let res: Response;",
  "  try {",
  "    res = await fetch(NEXA.url + \"/rest/v1/rpc/\" + name, {",
  "      method: \"POST\",",
  "      headers: { \"Content-Type\": \"application/json\", apikey: NEXA.key, Authorization: \"Bearer \" + NEXA.key },",
  "      body: JSON.stringify({ p_site: NEXA.site, p_visitor: visitorKey(), ...args }),",
  "    });",
  "  } catch {",
  "    throw new Error(\"No connection. Please try again.\");",
  "  }",
  "  if (!res.ok) {",
  "    let msg = \"\";",
  "    try {",
  "      msg = String((await res.json()).message || \"\");",
  "    } catch {",
  "      // not json",
  "    }",
  "    if (/too many/i.test(msg)) throw new Error(\"Too many requests right now. Please try again later.\");",
  "    if (/limit reached|too big/i.test(msg)) throw new Error(\"Storage limit reached.\");",
  "    if (/not found/i.test(msg)) throw new Error(\"Item not found.\");",
  "    throw new Error(\"Could not save. Please try again.\");",
  "  }",
  "  const text = await res.text();",
  "  return text ? JSON.parse(text) : null;",
  "}",
  "",
  "function fromServer(r: { id: string; data: Record<string, unknown>; created_at: string }): Row {",
  "  return { ...(r.data || {}), id: r.id, createdAt: r.created_at };",
  "}",
  "",
  "/**",
  " * Saved data for this site. Each visitor sees only their own items.",
  " *   const tasks = db(\"tasks\");",
  " *   const all = await tasks.list();                  // oldest first",
  " *   const t = await tasks.add({ title: \"Buy milk\", done: false });",
  " *   await tasks.update(t.id, { done: true });        // merges the given fields",
  " *   await tasks.remove(t.id);",
  " * Preview mode (inside NEXA AI): the data is kept in this browser only, for testing.",
  " * Methods throw an Error with a friendly message when something goes wrong.",
  " */",
  "export function db(collection: string) {",
  "  const name = String(collection || \"\").trim().toLowerCase().slice(0, 40);",
  "  if (!/^[a-z0-9 _-]{1,40}$/.test(name)) throw new Error(\"Bad collection name: use letters, numbers, space, - or _\");",
  "  const testKey = \"nexa-test-db:\" + name;",
  "  const readTest = (): Row[] => {",
  "    try {",
  "      return JSON.parse(localStorage.getItem(testKey) || \"[]\");",
  "    } catch {",
  "      return [];",
  "    }",
  "  };",
  "  const writeTest = (rows: Row[]) => {",
  "    try {",
  "      localStorage.setItem(testKey, JSON.stringify(rows.slice(-200)));",
  "    } catch {",
  "      // storage may be blocked",
  "    }",
  "  };",
  "",
  "  return {",
  "    async list(): Promise<Row[]> {",
  "      if (!NEXA.site) return readTest();",
  "      const rows = (await rpc(\"data_list\", { p_collection: name })) || [];",
  "      return rows.map(fromServer);",
  "    },",
  "    async add(data: Record<string, unknown>): Promise<Row> {",
  "      const fields = cleanFields(data);",
  "      if (!NEXA.site) {",
  "        const row: Row = { ...fields, id: \"t\" + randomId(6), createdAt: new Date().toISOString() };",
  "        writeTest([...readTest(), row]);",
  "        return row;",
  "      }",
  "      return fromServer(await rpc(\"data_add\", { p_collection: name, p_data: fields }));",
  "    },",
  "    async update(id: string, patch: Record<string, unknown>): Promise<Row> {",
  "      const fields = cleanFields(patch);",
  "      if (!NEXA.site) {",
  "        const rows = readTest();",
  "        const i = rows.findIndex((r) => r.id === id);",
  "        if (i < 0) throw new Error(\"Item not found.\");",
  "        rows[i] = { ...rows[i], ...fields };",
  "        writeTest(rows);",
  "        return rows[i];",
  "      }",
  "      return fromServer(await rpc(\"data_update\", { p_collection: name, p_id: id, p_data: fields }));",
  "    },",
  "    async remove(id: string): Promise<void> {",
  "      if (!NEXA.site) {",
  "        writeTest(readTest().filter((r) => r.id !== id));",
  "        return;",
  "      }",
  "      await rpc(\"data_remove\", { p_collection: name, p_id: id });",
  "    },",
  "  };",
  "}",
  "",
];

export const SDK_SOURCE = SDK_LINES.join("\n");

/** The two extra files for a run: `cfg` null = preview/test mode. */
export function backendFiles(cfg: BackendConfig | null): Record<string, string> {
  const c = cfg ?? { site: "", url: "", key: "" };
  return {
    "/nexa.ts": SDK_SOURCE,
    "/nexa-config.ts": "export const NEXA = " + JSON.stringify({ site: c.site, url: c.url.replace(/\/$/, ""), key: c.key }) + ";\n",
  };
}

/** True when some file imports the NEXA SDK. */
export function usesBackend(files: Record<string, string>): boolean {
  return Object.values(files).some((code) => /from\s+['"][./]*\/?nexa['"]/.test(code));
}
