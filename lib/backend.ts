export const SDK_SOURCE = SDK_LINES.join("\n") + "\n" + TEST_CORE_SOURCE;

/** The two extra files for a run: `cfg` null = preview/test mode. */
export function backendFiles(cfg: BackendConfig | null): Record<string, string> {
  const c = cfg ?? { site: "", url: "", key: "" };
  return {
    "/nexa.ts": SDK_SOURCE,
    "/nexa-config.ts": "export const NEXA = " + JSON.stringify({ site: c.site, url: c.url.replace(/\/$/, ""), key: c.key }) + ";\n",
  };
}

/** True when some file imports the NEXA SDK. */
export function usesBackend(files: Record<string, string>): boolean {
  return Object.values(files).some((code) => /from\s+['"][./]*\/?nexa['"]/.test(code));
}
